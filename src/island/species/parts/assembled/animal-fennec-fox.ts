/**
 * The fennec fox — **the ear animal**, and the one species in this pack that
 * `box-06` was waiting for.
 *
 * ONE SPECIES, ONE FILE. `register.ts` says why the one appended line in
 * `index.ts` is the whole of the wiring.
 *
 * ## The ear is the animal, and the ear decides everything else
 *
 * A fennec is a fox the size of a kitten with the largest ears of any canid on
 * earth. There is exactly one shape in the bank that can say that: **`box-06`
 * and its mirror `box-07`, the bunny's tall upright ear, 0.481975 x 0.913298 x
 * 0.305836 — the biggest ear in the pack by a distance**, and until now unspent.
 * The next tallest is the tiger's `wedge-16` at 0.388582, which is 0.43 of it.
 *
 * **The transfer is EXACT rather than an inference, and here is the proof.** The
 * bunny wears this ear on `box-03`, the plain 1.250 cube, which is the hull this
 * species also wears — so the donor transfer (§8) is a recovery on the same
 * shell rather than a carry-over between two:
 *
 *   - join at this cube's TOP FACE, `y = 1.43125`
 *   - sink the bunny's own measured `sunkFractionMean` of 0.366259, which on an
 *     extent of 0.913298 is 0.334504 of burial
 *   - the ear's centre therefore lands at 1.43125 + (0.456649 - 0.334504) =
 *     **y = 1.553395**
 *   - and the bank's recorded offset for the shape, which was not used to get
 *     there, is **1.553396**
 *
 * **One part in a million.** That agreement is the whole evidence the placement
 * is Kenney's and not ours — the same standard `animal-squirrel.ts` holds its cat
 * ear to (1.404572 against 1.404599) and `animal-mouse.ts` its koala dish. The
 * x = 0.286975 and z = 0.347082 are the bunny's own, untouched by the join.
 *
 * ## THE HEIGHT, WHICH IS THE TIGHTEST NUMBER IN THIS COLLECTION
 *
 * The ear's crown is 1.553395 + 0.456649 = **2.010044**, and `PACK_HEIGHT_MAX`
 * is **2.02**. This animal clears the pack's own ceiling by **0.009956** — half
 * a percent — and it was measured with `pets:creature` before anything else was
 * chosen, because a build that gets its face right and then measures 2.03 is a
 * build that starts again.
 *
 * Two things follow and both are binding on anyone editing this file:
 *
 *   1. **Nothing may stand above the ear.** The tail trails rather than being
 *      carried up the rear chamfer — `animal-squirrel.ts` does the latter with
 *      this same `box-23` and reaches 1.976 on a hull with no ears on it at all.
 *      Both together would be over. The eye card tops out at 1.141 and the hull
 *      at 1.43125, so the ear is alone up there and must stay alone.
 *   2. **If it were over, the answer would be a SHORTER EAR and never a shaved
 *      hull.** `HullDef.stretch` is `never` and there is no dial; the honest
 *      alternative is `wedge-16` at 0.389 tall, which is a different and much
 *      smaller animal. It is not needed, and it is written down so nobody
 *      rediscovers the question under pressure.
 *
 * ## The ear is ONE COLOUR, and that is a measurement rather than a choice
 *
 * A real fennec's ear is pale inside with a darker rim. Recorded as considered
 * and refused, because the bank cannot say it: **`box-06` has exactly one atlas
 * band over all 60 of its triangles.** The two ears that DO carry Kenney's own
 * inner-ear cut are `box-02` (band 7, 10 triangles on its forward face — see
 * `animal-raccoon.ts`) and `wedge-16` (band 5, 7 triangles), and both are less
 * than half this one's height. **The biggest ear in the pack is the only one with
 * no cut in it**, so a two-tone fennec ear would have to be either a smaller ear
 * or invented geometry, and it is neither.
 *
 * What is done instead costs nothing and is honest: the ear is painted from the
 * PALE slot entire. Head-on and from above — which is where the island's camera
 * actually is — a fennec reads as two big cream ears over a sandy body, and that
 * is the impression the one colour available buys.
 *
 * ## Every other number, and where it came from
 *
 *   - **The hull, the legs and the belly are the pack's own**, and the hull is
 *     not mentioned below at all because `box-03` at `[0, 0.80625, 0]` is what
 *     `defineCreature` gives a definition that says nothing — and because it is
 *     the shell the ear transfer above depends on. Four `box-01` sunk 0.408163 on
 *     the row at y = 0.18125 that never moves. The belly is **8/16**, the tiger's
 *     mammal line made exact: the only point on the pack's 1/16 grid inside §7's
 *     measured 0.4808-0.5481 zone, and also this cube's own equator.
 *
 *   - **THE EYES ARE `plate-14`, THE PANDA'S — THE BIGGEST IN THE PACK, UNSPENT —
 *     AND ITS BANDS ARE THE OTHER WAY ROUND.** 0.435472 x 0.442601 against the
 *     default card's 0.400 x 0.320208; the pack's whole eye range is 1.44x, so
 *     this is as big as a night animal's eye is allowed to get and stretching one
 *     is forbidden outright (rule 5).
 *
 *     The find is in its cut. On `plate-01` band 15 is the PUPIL — 10 small
 *     triangles — and band 3 is the 17-triangle sclera around it. On `plate-14`
 *     it is inverted: **band 15 is 40 triangles spanning the whole card
 *     (+/-0.2177, +/-0.2213) and band 3 is a 17-triangle patch off-centre and
 *     high (x -0.1240 to 0.1354, y -0.0707 to 0.1457)**. The builder always sends
 *     band 15 to `PACK_PUPIL`, so this card builds **a nearly all-dark eye with a
 *     single off-centre pale glint** — which is exactly a nocturnal animal's eye,
 *     for no geometry, no stretch and no new mechanism. Nothing was done to get
 *     that; it is what the panda's own card does when it is worn.
 *
 *   - **The muzzle is `tube-01`, the beaver's, and it is the SMALLEST in the
 *     bank** — 0.311961 x 0.193416 x 0.171605, against the fox's own `tube-06` at
 *     0.532 long. A fennec's face is a fox's face at kitten scale and the muzzle
 *     is the part that has to say so, since the hull cannot. Joined at the front
 *     face z = 0.625 and sunk its own 0.000, its centre lands on **z = 0.710803,
 *     the beaver's own recorded offset**; and because `box-03`'s recorded offset
 *     IS the beaver's hull centre, the height 0.815078 transfers with certainty
 *     rather than by argument.
 *
 *   - **The nose is `box-22`, the fox's own, sunk 0.5 — the recovery
 *     `animal-raccoon.ts` derives.** In short: the bank records this shape's
 *     burial as 0.000 and that is measured against the HULL, where it is true.
 *     The fox does not wear its nose on its hull, it wears it on its muzzle, and
 *     against the muzzle's own placed front plane (0.856420) the bank's recorded
 *     centre (0.856799) is 3.8e-4 away — the fox centres the nose-tip on the
 *     muzzle's front, which on a mirror-symmetric part is `sink: 0.5` exactly.
 *     The fox is this shape's only donor, so that is the whole of what the pack
 *     says about it, and it carries to a shorter muzzle unchanged. `on: 'snout'`
 *     still anchors it to the real placed plane rather than to arithmetic.
 *
 *     `pets:creature` marks it **`sunk 0.078 THIN`**, which is right to print and
 *     wrong to read as a fault, exactly as on `animal-salamander.ts`'s tail:
 *     0.1249 is §3's floor for an EAR and 0.078 is half of a nose 0.155703 deep.
 *
 *   - **THE TAIL IS `box-23`, THE FOX'S BRUSH, AND A FENNEC IS A FOX.** This is
 *     the one place in this collection where taking that shape needs no argument
 *     at all: `animal-wolf.ts` refuses it because a wolf is not a fox and the
 *     brush reads as one whatever colour it is painted, and that reasoning is
 *     precisely why it belongs here. Round section (0.910248 on both axes to six
 *     decimals), taper 0.961469, 1.67x the volume of any other tail — a fox's
 *     tail, on a fox.
 *
 *     Pure donor transfer: its own `z -1` facing, its own 0.177404 burial, no
 *     spin, no stretch and no `at`, so its centre recovers the fox's own recorded
 *     **z = -0.918642**. It trails, and §1 above is why.
 *
 *   - **The black tip is Kenney's own cut, and it is free.** Band 5 is 30 of the
 *     brush's 92 triangles, over local y -0.0238 to +0.4551 and z -0.4551 to
 *     +0.0238 — the shape faces `z -1`, so that is **the top half of the TIP
 *     half**, and it is where the real fox's tail changes colour. A fennec's tail
 *     is black-tipped; painted `mark` this is that, with no card and no geometry.
 *     It wraps the upper half only, which on a tip rather than a ring is a much
 *     smaller loss than it is on `animal-raccoon.ts` — stated so the difference
 *     between the two uses of the same band is on the record.
 *
 *   - **`box-23` is shared** with `animal-squirrel`, which carries it up the rear
 *     chamfer, and with `animal-raccoon`, which paints the same band for a tail
 *     tip rather than a black one. Reuse is house style; Kenney drew one leg and
 *     used it 86 times.
 *
 * ## THE PALETTE IS NEW AND NOBODY HAS SIGNED IT OFF
 *
 * This species has never been in a collection file, so it has never been given
 * colours. Every one below is the first ever proposed for it and every one is
 * marked UNREVIEWED. **Joe should look at them**, particularly the decision to
 * paint the whole ear from the pale slot, which is the §2 above made visible.
 *
 * **Flagged**, for the height and for the palette. No rule was strained: nothing
 * is stretched at all and there is no non-uniform stretch anywhere on this
 * animal. Measured on the built model — height **2.0100** inside 1.43-2.02 with
 * 0.0100 to spare, feet on y = 0; keep-out **1.124**, UNDER the fox's own 1.154
 * despite wearing the fox's own tail, because the muzzle is the bank's shortest
 * and the nose is buried in it; 611 triangles inside 422-951, 517 vertices inside
 * 405-1626 and 389 in the body inside 236-1114.
 */
